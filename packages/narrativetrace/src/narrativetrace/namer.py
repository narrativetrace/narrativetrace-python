def _validate(label: str, words: tuple[str, ...], expected: int) -> None:
    if len(words) != expected:
        raise ValueError(f"{label} has {len(words)} words, expected {expected}")
    for index, word in enumerate(words):
        if not 3 <= len(word) <= 6:
            raise ValueError(f'{label}[{index}] = "{word}" length {len(word)} outside 3-6 range')


_validate("ADJECTIVES", _ADJECTIVES, 256)
_validate("NOUNS", _NOUNS, 512)
_validate("VERBS", _VERBS, 256)


def trace_name(hex_value: str) -> str:
    """Derives a three-word "adjective noun verb" phrase from a 32-char hex trace id."""
    bits = int(hex_value[:7], 16)
    adjective = (bits >> 20) & 0xFF
    noun = (bits >> 11) & 0x1FF
    verb = (bits >> 3) & 0xFF
    return f"{_ADJECTIVES[adjective]} {_NOUNS[noun]} {_VERBS[verb]}"
